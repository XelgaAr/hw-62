export function collection(seed) {
  const rows = new Map(seed.map(row => [row.id, { ...row }]))
  let lastId = Math.max(0, ...rows.keys())
  return {
    all: () => [...rows.values()],
    get: id => rows.get(id),
    save(data, id = ++lastId) {
      const row = { ...data, id }
      rows.set(id, row)
      return row
    },
    delete: id => rows.delete(id)
  }
}

export const createCatalog = () => ({ users: collection(contributors), articles: collection(observations) })
